#!/usr/bin/env python3
"""Gemini / AGY long-horizon session canary: mint, score, hydrate, hand back.

The operational canary remains the shared 8/10 recall test.  Gemini adds the
v1.3 hydration gate after PASS and closes its exact lease after FAIL-HANDOFF.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import UTC, datetime
from pathlib import Path

from lu_machinery.common.epic_selector import validate_epic
from lu_machinery.common.repo_root import state_root
from lu_machinery.session_canary import handoff_select, shared_hydration
from lu_machinery.session_canary import recall_core as _gl

# This package's import name, as ``python -m`` names its modules (derived once, in recall_core).
_PACKAGE = _gl._PACKAGE

_HOLDER_AGENT = "gemini"
_HOLDER_HARNESS = "agy"


def _utc_now() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _epic_dir(repo: Path, epic: str) -> Path:
    validate_epic(epic)
    return repo / ".claude" / f"{epic}-epic"


def _cold_start_body(
    *,
    epic: str,
    stream_id: str,
    lease_summary: str,
) -> str:
    return f"""# Gemini cold-start — {epic} / {stream_id}

> Generated by `{_PACKAGE}.gemini_lane bootstrap` at {_utc_now()}.
> **No secrets.** Drive only the next unblocked action for this stream.

## Identity
- **Seat:** Gemini / AGY orchestrator
- **Epic:** `{epic}`
- **Stream:** `{stream_id}`
- **Lease:** {lease_summary}

## Immediate steps
1. Run `lu-driver-state render --lane {epic}` and read the newest active handoff note with `lu-driver-state show <its ID>`. Then read the stream tail.
2. Mint a canary: `.venv/bin/python -m {_PACKAGE}.gemini_lane mint --epic {epic} --stream {stream_id}`.
3. Score from memory. PASS auto-hydrates. FAIL-HANDOFF closes the exact lease.
4. Continue only when the hydration capsule has `execution_allowed: true`.
"""


def _stream_id(args: argparse.Namespace) -> str:
    return _gl._stream_id(args)


def _read_lease_environment(env_path: Path) -> dict[str, str]:
    """Parse the launcher receipt without sourcing a shell file."""
    environment: dict[str, str] = {}
    for line in env_path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("export SESSION_STREAM_") or "=" not in line:
            continue
        key, value = line.removeprefix("export ").split("=", 1)
        environment[key] = value.strip().strip("'\"")
    return environment


def _close_exact_lease(repo: Path, epic: str) -> bool:
    """Close only the lease recorded by this lane's launcher receipt."""
    env_path = _epic_dir(repo, epic) / "session-lease.env"
    if not env_path.is_file():
        return False
    environment = _read_lease_environment(env_path)
    try:
        from lu_machinery.session_streams.db import SessionStreamDatabase
        from lu_machinery.session_streams.hooks import clean_exit_hook, lease_from_environment
        from lu_machinery.session_streams.store import SessionStreamStore

        clean_exit_hook(SessionStreamStore(SessionStreamDatabase()), lease_from_environment(environment))
    except (OSError, ValueError, RuntimeError):
        return False
    return True


def cmd_hydrate(args: argparse.Namespace) -> int:
    stream_id = _stream_id(args)
    lane = os.environ.get("SESSION_STREAM_AGENT", _HOLDER_AGENT)
    if lane != _HOLDER_AGENT:
        # The registry imports the bridge; bare-provider hooks do not need it.
        from lu_machinery.orchestration.handoff_slot_registry import registered_slots

        if lane not in registered_slots(_HOLDER_AGENT):
            print("ACTION: hydration blocked — unregistered lane identity for this provider.", file=sys.stderr)
            return 2
    capsule, attempts = shared_hydration.build_hydration_capsule_with_retry(stream_id, lane)
    print(f"hydration_attempts: {attempts}", file=sys.stderr)
    print(json.dumps(capsule, ensure_ascii=False, sort_keys=True))
    if not capsule["execution_allowed"]:
        print("ACTION: hydration blocked — do not continue this driver.", file=sys.stderr)
        return 2
    print("ACTION: hydration ready — continue the current driver.")
    return 0


def cmd_score(args: argparse.Namespace) -> int:
    """Score shared canary, then route PASS and FAIL-HANDOFF through their paths."""
    args.db_handoff = True
    score_rc = _gl.cmd_score(args)
    if score_rc == 0:
        hydrate_rc = cmd_hydrate(args)
        if hydrate_rc != 0:
            _close_exact_lease(Path(args.repo).resolve(), args.epic)
        return hydrate_rc
    if score_rc == 2:
        closed = _close_exact_lease(Path(args.repo).resolve(), args.epic)
        detail = "exact lease closed" if closed else "exact lease receipt unavailable"
        print(f"ACTION: FAIL-HANDOFF — {detail}; exit this Gemini driver.")
    return score_rc


def cmd_bootstrap(args: argparse.Namespace) -> int:
    """Write a non-authoritative cold-start board; launchers own lease acquisition."""
    repo = Path(args.repo).resolve()
    epic = args.epic.strip().lower()
    validate_epic(epic)
    args.epic = epic
    stream_id = _stream_id(args)
    epic_path = _epic_dir(repo, epic)
    epic_path.mkdir(parents=True, exist_ok=True)
    board_path = epic_path / "GEMINI-COLD-START.md"
    board_path.write_text(
        _cold_start_body(
            epic=epic,
            stream_id=stream_id,
            lease_summary=f"stream {stream_id}; verify launcher-owned lease before driving",
        ),
        encoding="utf-8",
    )
    print(f"Bootstrapped Gemini cold-start board: {board_path.relative_to(repo)}")
    return 0


def cmd_protocol(args: argparse.Namespace) -> int:
    stream = _stream_id(args)
    print(
        f"""## Gemini lane canary

Stream: **{stream}**

1. Mint 10 durable anchors.
2. Score from memory (8/10 PASS threshold).
3. PASS → emit and validate HydrationCapsuleV1 v1.3, then continue only if allowed.
4. FAIL-HANDOFF → record a stream handback, close the exact lease, and exit.
"""
    )
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    canary_dir = Path(args.out_dir) if args.out_dir else _epic_dir(Path(args.repo).resolve(), args.epic) / "canary"
    verdict = canary_dir / "last_verdict.json"
    print(f"Gemini canary status: {'verdict present' if verdict.is_file() else 'not yet scored'} for {args.epic}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog=f"python -m {_PACKAGE}.gemini_lane",
        description="Run the lane's recall canary. Mint after recording a driver-state handoff note.",
        epilog=(
            "Examples:\n  %(prog)s mint --epic devops\n"
            "  %(prog)s score --epic devops --answers answers.json\n"
            "Outputs: cold-start board, recall artifacts, and score or hydration status.\n"
            "Exit codes: 0 success, 1 unavailable anchors or inputs, 2 FAIL-HANDOFF or refusal.\n"
            "Related: driver-state handoff authority, #511 and #512."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--repo", type=Path, default=None, help="State root; default is the shared-state anchor")
    sub = parser.add_subparsers(dest="subcommand", required=True)

    boot = sub.add_parser("bootstrap", help="Write Gemini cold-start board")
    boot.add_argument("--epic", required=True, help="Lane selector, for example devops.")
    boot.add_argument("--stream", help="Stream ID. Default: resolve it from the lane.")
    boot.set_defaults(func=cmd_bootstrap)

    mint = sub.add_parser("mint", help="Freeze 10 recall anchors from the DB note and lane stream")
    mint.add_argument("--epic", required=True, help="Lane selector, for example devops.")
    mint.add_argument("--stream", help="Stream ID. Default: resolve it from the lane.")
    mint.add_argument("--out-dir", help="Canary artifacts. Default: .claude/<lane>-epic/canary.")
    mint.add_argument("--stream-limit", type=int, default=40, help=handoff_select.STREAM_LIMIT_HELP)
    mint.set_defaults(func=_gl.cmd_mint, db_handoff=True)

    questions = sub.add_parser("questions", help="Print canary questions without answers")
    questions.add_argument("--epic", default="harness", help="Lane selector. Default: harness.")
    questions.add_argument("--out-dir", help="Canary artifacts. Default: .claude/<lane>-epic/canary.")
    questions.add_argument("--out", help="Questions JSON destination. Default: questions.json in the artifact directory.")
    questions.set_defaults(func=_gl.cmd_questions)

    score = sub.add_parser("score", help="Score then hydrate/hand back")
    score.add_argument("--epic", default="harness", help="Lane selector. Default: harness.")
    score.add_argument("--stream", help="Stream ID. Default: resolve it from the lane.")
    score.add_argument("--out-dir", help="Canary artifacts. Default: .claude/<lane>-epic/canary.")
    score.add_argument("--answers", required=True, help="JSON object mapping anchor IDs to recalled answers.")
    score.add_argument("--context-tokens", type=int, default=0, help="Observed context tokens. Default: 0 (unknown).")
    score.add_argument(
        "--model", default="gemini-4-hydrogen-medium",
        help="Model recorded in the score log. Default: %(default)s.",
    )
    score.add_argument(
        "--pass-ratio", type=float, default=_gl.DEFAULT_PASS_RATIO,
        help="Required fraction of correct answers. Default: %(default)s.",
    )
    score.add_argument(
        "--threshold", type=float, default=_gl.DEFAULT_SIM_THRESHOLD,
        help="Required answer similarity. Default: %(default)s.",
    )
    score.set_defaults(func=cmd_score)

    hydrate = sub.add_parser("hydrate", help="Emit a validated v1.3 hydration capsule")
    hydrate.add_argument("--epic", required=True, help="Lane selector, for example devops.")
    hydrate.add_argument("--stream", help="Stream ID. Default: resolve it from the lane.")
    hydrate.set_defaults(func=cmd_hydrate)

    status = sub.add_parser("status", help="Show canary verdict presence")
    status.add_argument("--epic", required=True, help="Lane selector, for example devops.")
    status.add_argument("--out-dir", help="Canary artifacts. Default: .claude/<lane>-epic/canary.")
    status.set_defaults(func=cmd_status)

    protocol = sub.add_parser("protocol", help="Print canary lifecycle")
    protocol.add_argument("--epic", required=True, help="Lane selector, for example devops.")
    protocol.add_argument("--stream", help="Stream ID. Default: resolve it from the lane.")
    protocol.set_defaults(func=cmd_protocol)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    args.epic = args.epic.strip().lower()
    try:
        if args.repo is None:
            args.repo = state_root()
        # Hydration/protocol use routing aliases, without constructing epic paths.
        if args.subcommand not in {"hydrate", "protocol"}:
            validate_epic(args.epic)
        return int(args.func(args))
    except (handoff_select.StreamResolutionError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
